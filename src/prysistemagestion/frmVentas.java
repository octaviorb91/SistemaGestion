    private void btnBuscarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarClienteActionPerformed
        String dniABuscar = txtDniBusqueda.getText().trim();
    
        if (dniABuscar.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un DNI para buscar.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        conexionBD conexion = new conexionBD();
        java.sql.Connection con = null;
        java.sql.PreparedStatement ps = null;
        java.sql.ResultSet rs = null;

        try {
            con = conexion.conectar();
            // Buscamos al cliente por DNI y verificamos que esté activo
            String sql = "SELECT idCliente, nombre, apellido FROM clientes WHERE dni = ? AND activo = true";
            ps = con.prepareStatement(sql);
            ps.setString(1, dniABuscar);

            rs = ps.executeQuery();

            if (rs.next()) {
                // Si lo encuentra, guardamos el ID oculto y unimos nombre y apellido
                txtIdCliente.setText(String.valueOf(rs.getInt("idCliente")));

                String nombreCompleto = rs.getString("nombre") + " " + rs.getString("apellido");
                txtNombreCliente.setText(nombreCompleto);
            } else {
                // Si no existe o está inactivo
                javax.swing.JOptionPane.showMessageDialog(this, "Cliente no encontrado o inactivo.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                txtIdCliente.setText("");
                txtNombreCliente.setText("");
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al buscar cliente:\n" + e.getMessage(), "Error BD", javax.swing.JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) rs.close();
                if (ps != null) ps.close();
                conexion.desconectar();
            } catch (java.sql.SQLException ex) { }
        }
    }//GEN-LAST:event_btnBuscarClienteActionPerformed

    private void btnBuscarArticuloActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarArticuloActionPerformed
        String codigoABuscar = txtCodigoArticulo.getText().trim();
    
        if (codigoABuscar.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el código del artículo.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        conexionBD conexion = new conexionBD();
        java.sql.Connection con = null;
        java.sql.PreparedStatement ps = null;
        java.sql.ResultSet rs = null;

        try {
            con = conexion.conectar();
            // Buscamos por idArticulo y verificamos que esté activo
            String sql = "SELECT nombre, precio, stock FROM articulos WHERE idArticulo = ? AND activo = true";
            ps = con.prepareStatement(sql);
            ps.setInt(1, Integer.parseInt(codigoABuscar));

            rs = ps.executeQuery();

            if (rs.next()) {
                txtNombreArticulo.setText(rs.getString("nombre"));
                txtPrecioArticulo.setText(String.valueOf(rs.getDouble("precio")));
                txtStockArticulo.setText(String.valueOf(rs.getInt("stock")));
                txtCantidad.setText("1"); // Ponemos 1 por defecto
                txtCantidad.requestFocus(); // Mandamos el cursor al campo cantidad
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Artículo no encontrado o inactivo.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                txtNombreArticulo.setText("");
                txtPrecioArticulo.setText("");
                txtStockArticulo.setText("");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El código del artículo debe ser numérico.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al buscar el artículo:\n" + e.getMessage(), "Error BD", javax.swing.JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) rs.close();
                if (ps != null) ps.close();
                conexion.desconectar();
            } catch (java.sql.SQLException ex) { }
        }
    }//GEN-LAST:event_btnBuscarArticuloActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String codigo = txtCodigoArticulo.getText().trim();
        String nombre = txtNombreArticulo.getText().trim();
        String precioTexto = txtPrecioArticulo.getText().trim();
        String stockTexto = txtStockArticulo.getText().trim();
        String cantidadTexto = txtCantidad.getText().trim();

        if (codigo.isEmpty() || nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debe buscar y seleccionar un artículo.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (cantidadTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese una cantidad.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int cantidad = Integer.parseInt(cantidadTexto);
            int stockDisponible = Integer.parseInt(stockTexto);
            double precioUnitario = Double.parseDouble(precioTexto);

            if (cantidad <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a cero.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (cantidad > stockDisponible) {
                javax.swing.JOptionPane.showMessageDialog(this, "Stock insuficiente. Stock disponible: " + stockDisponible, "Stock excedido", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            double subtotal = precioUnitario * cantidad;

            javax.swing.table.DefaultTableModel modeloCarrito = (javax.swing.table.DefaultTableModel) tblCarrito.getModel();

            // Si es la primera vez y tiene filas vacías por defecto de NetBeans, las limpiamos para que no molesten
            if (modeloCarrito.getRowCount() > 0 && modeloCarrito.getValueAt(0, 0) == null) {
                modeloCarrito.setRowCount(0);
            }

            Object[] fila = new Object[5];
            fila[0] = codigo;
            fila[1] = nombre;
            fila[2] = cantidad;
            fila[3] = precioUnitario;
            fila[4] = subtotal;

            // ¡Magia aquí! insertRow(0, fila) agrega el producto SIEMPRE arriba de todo
            modeloCarrito.insertRow(0, fila);

            actualizarTotalVenta();

            // Limpiamos los campos del buscador
            txtCodigoArticulo.setText("");
            txtNombreArticulo.setText("");
            txtPrecioArticulo.setText("");
            txtStockArticulo.setText("");
            txtCantidad.setText("");
            txtCodigoArticulo.requestFocus();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "La cantidad debe ser un número entero válido.", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    // Método auxiliar para sumar todos los subtotales de la tabla carrito
    private void actualizarTotalVenta() {
        javax.swing.table.DefaultTableModel modeloCarrito = (javax.swing.table.DefaultTableModel) tblCarrito.getModel();
        double totalGeneral = 0.0;

        for (int i = 0; i < modeloCarrito.getRowCount(); i++) {
            Object valorColumna = modeloCarrito.getValueAt(i, 4);

            // Validamos estrictamente que la celda no sea nula ni esté vacía
            if (valorColumna != null && !valorColumna.toString().trim().isEmpty()) {
                try {
                    double subtotalFila = Double.parseDouble(valorColumna.toString());
                    totalGeneral += subtotalFila;
                } catch (NumberFormatException e) {
                    // Ignoramos si hay algún texto raro en la celda
                }
            }
        }

        txtTotal.setText(String.format("%.2f", totalGeneral));
    }//GEN-LAST:event_btnAgregarActionPerformed

