    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String idTexto = txtCodigo.getText().trim();
    
        if (idTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione un cliente de la tabla para eliminar.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int respuesta = javax.swing.JOptionPane.showConfirmDialog(this, 
                "¿Está seguro que desea eliminar permanentemente a este cliente?", 
                "Confirmar Eliminación", 
                javax.swing.JOptionPane.YES_NO_OPTION, 
                javax.swing.JOptionPane.QUESTION_MESSAGE);

        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
            conexionBD conexion = new conexionBD();
            java.sql.Connection con = null;
            java.sql.PreparedStatement ps = null;

            try {
                con = conexion.conectar();

                //Borramos donde el idCliente coincida
                String sql = "DELETE FROM clientes WHERE idCliente=?";
                ps = con.prepareStatement(sql);
                ps.setInt(1, Integer.parseInt(idTexto));

                int resultado = ps.executeUpdate();

                if (resultado > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Cliente eliminado con éxito.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                    cargarTabla();
                    limpiarCampos();
                    habilitarCampos(false);
                }

            } catch (java.sql.SQLException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error al eliminar en la BD:\n" + e.getMessage(), "Error SQL", javax.swing.JOptionPane.ERROR_MESSAGE);
            } finally {
                try {
                    if (ps != null) ps.close();
                    conexion.desconectar();
                } catch (java.sql.SQLException ex) { }
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

